"""Generate the ZIP code table from the Census ZCTA gazetteer.

Usage: python3 tools/build_zips.py <YYYY_Gaz_zcta_national.txt>

Download the gazetteer (public domain) from
https://www.census.gov/geographies/reference-files/time-series/geo/gazetteer-files.html
and pass the extracted .txt. Writes source/gen/zips_gen.{c,h}.
"""

import csv
import sys
from pathlib import Path

GEN = Path(__file__).resolve().parent.parent / "source" / "gen"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = Path(sys.argv[1])
    with source.open(newline="") as f:
        rows = sorted(
            (int(r["GEOID"]), float(r["INTPTLAT"]), float(r["INTPTLONG"].strip()))
            for r in csv.DictReader(f, delimiter="|")
        )

    # Plain C types so host tests can link the table.
    h = [
        f"// Generated by tools/build_zips.py from {source.name}. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "\tuint32_t zip;",
        "\tfloat lat, lon; // internal point of the ZIP Code Tabulation Area",
        "} ZipInfo;",
        "",
        f"#define ZIP_COUNT {len(rows)}",
        "extern const ZipInfo zip_info[ZIP_COUNT]; // sorted by zip",
        "",
    ]
    (GEN / "zips_gen.h").write_text("\n".join(h))
    c = [h[0], '#include "zips_gen.h"', "", "const ZipInfo zip_info[ZIP_COUNT] = {"]
    c += [f"\t{{ {z}, {lat}f, {lon}f }}," for z, lat, lon in rows]
    c += ["};", ""]
    (GEN / "zips_gen.c").write_text("\n".join(c))
    print(f"{len(rows)} ZIP codes")


if __name__ == "__main__":
    main()
